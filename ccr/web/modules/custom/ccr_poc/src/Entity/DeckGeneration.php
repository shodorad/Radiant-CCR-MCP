<?php

namespace Drupal\ccr_poc\Entity;

use Drupal\Core\Entity\ContentEntityBase;
use Drupal\Core\Entity\EntityTypeInterface;
use Drupal\Core\Field\BaseFieldDefinition;
use Drupal\ccr_poc\Snapshot;
use Drupal\node\NodeInterface;

/**
 * One slide of one deck: which template, which content, which items, which
 * version of that content, who generated it and when.
 *
 * A deck stops following the repository the moment it is downloaded. That drift
 * is the thing H5 exists to surface, and surfacing it needs four facts: which
 * content, which version of it, who generated it, and when.
 *
 * Staleness is deliberately *not* stored. A stored flag has to be maintained on
 * every node save, and the day that hook fails to run the dashboard starts
 * lying. Comparing the recorded version against the node's current one is one
 * line and cannot drift, so `isStale()` computes it every time it is asked.
 *
 * **A row is a slide, not a deck.** Unwelding phase 3 made a deck an ordered
 * list of (template, record, selection), so the rows sharing a `deck_id` *are*
 * the deck definition: regenerating replays them, and staleness is answered per
 * entry rather than per deck — which matters as soon as a deck draws on more
 * than one record, because "something in here is out of date" is not an
 * actionable sentence.
 *
 * Merging the definition and the log into one table is a deliberate small
 * choice, and it has a consequence worth stating: a deck exists because someone
 * generated it once. There is no saved-but-never-built deck. For a POC whose
 * demo is "press Generate", that is the whole lifecycle, and one table is one
 * table for the developer who has to maintain this.
 *
 * The entity id is still `ccr_deck_generation`, which is now a slight misnomer.
 * Renaming a content entity type in Drupal is a migration with no user-visible
 * benefit, so the name stayed and this paragraph exists instead.
 *
 * @ContentEntityType(
 *   id = "ccr_deck_generation",
 *   label = @Translation("Deck generation"),
 *   base_table = "ccr_deck_generation",
 *   entity_keys = {
 *     "id" = "id",
 *     "uuid" = "uuid",
 *     "label" = "content_title",
 *   },
 *   handlers = {
 *     "storage" = "Drupal\Core\Entity\Sql\SqlContentEntityStorage",
 *     "view_builder" = "Drupal\Core\Entity\EntityViewBuilder",
 *     "access" = "Drupal\Core\Entity\EntityAccessControlHandler",
 *   },
 *   admin_permission = "generate ccr decks",
 * )
 */
class DeckGeneration extends ContentEntityBase {

  public static function baseFieldDefinitions(EntityTypeInterface $entity_type): array {
    $fields = parent::baseFieldDefinitions($entity_type);

    $fields['content_nid'] = BaseFieldDefinition::create('integer')
      ->setLabel(t('Content'))
      ->setDescription(t('The node this deck was generated from.'))
      ->setRequired(TRUE);

    $fields['content_title'] = BaseFieldDefinition::create('string')
      ->setLabel(t('Content title'))
      ->setSetting('max_length', 255);

    // The node's `changed` timestamp at the moment of generation. This is the
    // "which version" fact, and the only thing staleness is decided on.
    $fields['content_changed'] = BaseFieldDefinition::create('integer')
      ->setLabel(t('Content version'))
      ->setDescription(t('The changed timestamp of the content when the deck was made.'))
      ->setRequired(TRUE);

    $fields['generated_by'] = BaseFieldDefinition::create('string')
      ->setLabel(t('Generated by'))
      ->setSetting('max_length', 64)
      ->setRequired(TRUE);

    $fields['generated_at'] = BaseFieldDefinition::create('created')
      ->setLabel(t('Generated'));

    $fields['channel'] = BaseFieldDefinition::create('string')
      ->setLabel(t('Channel'))
      ->setSetting('max_length', 32)
      ->setDefaultValue('pptx');

    // ---- the deck this slide belongs to (unwelding phase 3) ----

    $fields['deck_id'] = BaseFieldDefinition::create('string')
      ->setLabel(t('Deck'))
      ->setDescription(t('The deck these slides make up. Rows sharing this are one deck, in delta order.'))
      ->setSetting('max_length', 64);

    $fields['deck_label'] = BaseFieldDefinition::create('string')
      ->setLabel(t('Deck name'))
      ->setSetting('max_length', 255);

    $fields['delta'] = BaseFieldDefinition::create('integer')
      ->setLabel(t('Position'))
      ->setDescription(t('Where this slide sits in the deck.'))
      ->setDefaultValue(0);

    $fields['template'] = BaseFieldDefinition::create('string')
      ->setLabel(t('Template'))
      ->setDescription(t('The blueprint card id the renderer filled for this slide.'))
      ->setSetting('max_length', 64);

    // Which items of a repeating slot this slide uses, and in what order, as
    // the renderer's own shape: {"items": ["<key>", ...]}. Stored here and
    // never on the node — selection is the channel's business, and writing it
    // back to the repository would be the slide editing the business again.
    $fields['selection'] = BaseFieldDefinition::create('string_long')
      ->setLabel(t('Selection'))
      ->setDescription(t('Which items this slide shows, as JSON. Belongs to the deck, never to the record.'));

    // What the renderer said it put on this slide, as `POST /values` returned
    // it. `content_changed` answers *whether* the record moved; this answers
    // *what* moved, which is the only version of the question a person can act
    // on. See Snapshot.php for why the comparison cannot get long, and why the
    // renderer rather than this module is asked what reaches a slide.
    $fields['rendered'] = BaseFieldDefinition::create('string_long')
      ->setLabel(t('Rendered lines'))
      ->setDescription(t('The lines this slide carried when it was generated, as JSON.'));

    return $fields;
  }

  /** The selection this slide was built with, decoded. */
  public function getSelection(): array {
    $raw = $this->get('selection')->value;
    if (!$raw) {
      return [];
    }
    $decoded = json_decode($raw, TRUE);
    return is_array($decoded) ? $decoded : [];
  }

  /** The lines this slide carried when it was made. Empty if never captured. */
  public function getRenderedLines(): array {
    return Snapshot::lines($this->get('rendered')->value);
  }

  /**
   * Which lines have moved since this slide was generated.
   *
   * **Not guarded by the timestamp**, and that is the whole point. Skipping the
   * comparison when `changed` had not moved looked like a free optimisation and
   * was a false-negative generator: editing a capability pillar and saving the
   * paragraph does not touch the node's `changed`, because the node's own field
   * values did not change and `ChangedItem::preSave()` only bumps it when they
   * did. A deck quietly reported as current while the words on its slides had
   * moved is the exact failure this feature exists to prevent, so the cheap
   * check does not get to have an opinion.
   *
   * What it costs: one renderer call per slide per listing, memoised for the
   * request. The renderer is local, the record is small, and being right about
   * this is the product.
   *
   * @return array<int, array> the drift pairs, or [] when there is nothing to
   *   compare against — see ::canReportDrift().
   */
  public function drift(): array {
    if (!$this->canReportDrift()) {
      return [];
    }
    $node = $this->getNode();
    $selection = $this->getSelection();
    // Keyed by what the answer depends on. `changed` stays in the key so an
    // edit made mid-request is not served from a memo taken before it, even
    // though it no longer decides whether to ask.
    $key = implode('|', [
      $node->id(), $node->getChangedTime(), $this->get('template')->value, md5(json_encode($selection)),
    ]);

    // A written slide shows approved copy, not the record. What it would show
    // now is the copy approved now; if that approval is out of date there is
    // nothing current to compare with, and the timestamp answers alone.
    $written = \Drupal::service('ccr_poc.copy_store')->get($node, $this->get('template')->value);
    if ($written !== NULL && ($written['status'] !== 'approved' || \Drupal\ccr_poc\CopyStore::isStale($written, $node))) {
      return [];
    }
    $key .= $written ? '|' . md5(json_encode($written['copy'])) : '';

    static $memo = [];
    if (!array_key_exists($key, $memo)) {
      $memo[$key] = \Drupal::service('ccr_poc.renderer')
        ->values($node, $this->get('template')->value, $selection, $written['copy'] ?? NULL)['lines'] ?? NULL;
    }
    // The renderer could not be reached or refused the record. "Cannot tell" is
    // not "nothing changed": the caller keeps the timestamp's answer.
    if ($memo[$key] === NULL) {
      return [];
    }

    return Snapshot::drift($this->getRenderedLines(), $memo[$key]);
  }

  /**
   * Can this row say *what* changed, or only *that* something did?
   *
   * False for rows written before snapshots existed, and for the single-slide
   * path when the caller did not say which template it filled. Those rows are
   * still honest — they fall back to the timestamp — but a channel showing a
   * before/after needs to know it has nothing to quote rather than quoting an
   * empty list as agreement.
   */
  public function canReportDrift(): bool {
    return $this->getRenderedLines() !== [] && $this->getNode() !== NULL;
  }

  public function getNode(): ?NodeInterface {
    return \Drupal::entityTypeManager()->getStorage('node')->load($this->get('content_nid')->value);
  }

  /** Has the content moved since this deck was made? */
  public function isStale(): bool {
    $node = $this->getNode();
    return $node ? $node->getChangedTime() > (int) $this->get('content_changed')->value : FALSE;
  }

  /**
   * Record a generation, one row per person per content item.
   *
   * Upsert rather than append: "my decks" is a list of the deck each person is
   * currently holding, not an audit trail. Regenerating replaces the row, which
   * is what makes the stale flag clear.
   *
   * This is the single-slide path — the renderer's CLI and its HTTP service,
   * which generate one slide from one template and have no deck definition to
   * replay. A deck made through the CCR goes through ::saveDeck() instead.
   */
  public static function log(NodeInterface $node, string $generated_by, string $channel = 'pptx', string $template = ''): self {
    $storage = \Drupal::entityTypeManager()->getStorage('ccr_deck_generation');
    $existing = $storage->loadByProperties([
      'content_nid' => $node->id(),
      'generated_by' => $generated_by,
      'channel' => $channel,
      'deck_id' => self::soloDeckId($node, $generated_by),
    ]);

    /** @var self $entry */
    $entry = $existing ? reset($existing) : $storage->create([
      'content_nid' => $node->id(),
      'generated_by' => $generated_by,
      'channel' => $channel,
      'deck_id' => self::soloDeckId($node, $generated_by),
      'deck_label' => $node->label(),
      'delta' => 0,
      'template' => '',
    ]);
    $entry->set('content_title', $node->label());
    $entry->set('content_changed', $node->getChangedTime());
    $entry->set('generated_at', \Drupal::time()->getRequestTime());
    // Only when the caller said which template it filled. A snapshot taken
    // against a guessed template would describe a slide nobody made.
    if ($template !== '') {
      $entry->set('template', $template);
      $entry->set('rendered', self::capture($node, $template, []));
    }
    $entry->save();

    return $entry;
  }

  /**
   * Ask the renderer what it is about to put on this slide, and keep it.
   *
   * Taken at save time rather than read back from the file, because the .pptx
   * is bytes on somebody's laptop and the repository never sees it again. This
   * is the repository's own note of what it handed over.
   *
   * Returns NULL when the renderer cannot answer. That is stored as an absent
   * snapshot, which every reader treats as "cannot tell" and falls back to the
   * timestamp for — a deliberately different state from "nothing changed".
   */
  private static function capture(NodeInterface $node, string $template, array $selection, ?array $record = NULL): ?string {
    $values = \Drupal::service('ccr_poc.renderer')->values($node, $template, $selection, $record);
    return isset($values['lines']) ? json_encode($values) : NULL;
  }

  /** The deck a single-slide generation belongs to: one per person per record. */
  private static function soloDeckId(NodeInterface $node, string $generated_by): string {
    return 'solo-' . $node->id() . '-' . preg_replace('/[^a-z0-9]+/', '-', strtolower($generated_by));
  }

  /**
   * Save a deck definition, replacing whatever it held before.
   *
   * Replace rather than reconcile: a deck is a short ordered list somebody just
   * edited, and matching old rows to new ones by position would quietly keep a
   * stale `content_changed` on a slide whose template changed underneath it.
   *
   * @param array $entries
   *   Each: ['template' => id, 'node' => NodeInterface, 'selection' => array].
   */
  public static function saveDeck(string $deck_id, string $label, string $generated_by, array $entries, string $channel = 'pptx'): array {
    $storage = \Drupal::entityTypeManager()->getStorage('ccr_deck_generation');
    $storage->delete($storage->loadByProperties(['deck_id' => $deck_id]));

    $saved = [];
    foreach (array_values($entries) as $delta => $entry) {
      /** @var \Drupal\node\NodeInterface $node */
      $node = $entry['node'];
      $row = $storage->create([
        'deck_id' => $deck_id,
        'deck_label' => $label,
        'delta' => $delta,
        'template' => $entry['template'],
        'selection' => json_encode($entry['selection'] ?? []),
        'content_nid' => $node->id(),
        'content_title' => $node->label(),
        'content_changed' => $node->getChangedTime(),
        // A written slide's lines are its approved copy, which is what it
        // carried; the record's source material never reached the slide.
        'rendered' => self::capture($node, $entry['template'], $entry['selection'] ?? [], $entry['record'] ?? NULL),
        'generated_by' => $generated_by,
        'generated_at' => \Drupal::time()->getRequestTime(),
        'channel' => $channel,
      ]);
      $row->save();
      $saved[] = $row;
    }
    return $saved;
  }

  /** The slides of one deck, in order. */
  public static function loadDeck(string $deck_id): array {
    $storage = \Drupal::entityTypeManager()->getStorage('ccr_deck_generation');
    $rows = $storage->loadByProperties(['deck_id' => $deck_id]);
    usort($rows, fn($a, $b) => (int) $a->get('delta')->value <=> (int) $b->get('delta')->value);
    return $rows;
  }

  /**
   * Every deck, grouped, newest first.
   *
   * @return array<string, array{label: string, owner: string, generated: int,
   *   stale: int, slides: array}>
   */
  public static function decks(): array {
    $storage = \Drupal::entityTypeManager()->getStorage('ccr_deck_generation');
    $rows = $storage->loadMultiple($storage->getQuery()->accessCheck(FALSE)->execute());

    $decks = [];
    foreach ($rows as $row) {
      $id = $row->get('deck_id')->value ?: ('untracked-' . $row->id());
      $decks[$id]['label'] = $row->get('deck_label')->value ?: $row->get('content_title')->value;
      $decks[$id]['owner'] = $row->get('generated_by')->value;
      $decks[$id]['generated'] = max($decks[$id]['generated'] ?? 0, (int) $row->get('generated_at')->value);
      $decks[$id]['slides'][] = $row;
    }

    foreach ($decks as &$deck) {
      usort($deck['slides'], fn($a, $b) => (int) $a->get('delta')->value <=> (int) $b->get('delta')->value);
      $deck['stale'] = count(array_filter($deck['slides'], fn($s) => $s->isStale()));
    }
    unset($deck);

    uasort($decks, fn($a, $b) => $b['generated'] <=> $a['generated']);
    return $decks;
  }

}
